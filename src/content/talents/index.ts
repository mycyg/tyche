import type { Debuff, Talent } from '../../game/types';

export type TalentFamily = '临床直觉' | '文书合规' | '社交沟通' | '体质作息' | '运气命运' | '黑暗面';
export interface TalentDefinition extends Talent {
  family: TalentFamily;
  rarity: '常见' | '少见' | '稀有';
  weight: number;
  detail: string;
  source: string;
}
export interface DebuffDefinition extends Debuff {
  family: '体力' | '感知' | '情绪' | '关系' | '钱' | '行为';
  weight: number;
  recovery: string;
  source: string;
}
const source = '02_天赋与debuff.md';
const playerWords=(text:string)=>text.replace(/理智值?/g,'精神').replace(/心情/g,'情绪').replace(/声誉/g,'声望').replace(/行动力/g,'行动值').replace(/安慰/g,'安抚').replace(/首个节点/g,'首次处置').replace(/后续节点/g,'后续处置').replace(/每轮/g,'每局').replace(/本轮/g,'本局').replace(/一轮/g,'一局');
function talent(id: string, name: string, family: TalentFamily, rarity: TalentDefinition['rarity'], benefit: string, price: string, detail: string): TalentDefinition {
  return {id, name, family, rarity, weight: ({常见: 3, 少见: 2, 稀有: 1})[rarity], benefit:playerWords(benefit), price:playerWords(price), detail:playerWords(detail), source: `${source}#${id}`};
}

