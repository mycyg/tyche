export function probeEvidence(source: PresetSource, index: number, method: 'history' | 'observe' | 'comfort'): string {
  if (method === 'comfort') return '患者说明了拒绝的顾虑，经过解释愿意继续讨论安排。具体检查尚未执行，仍须就项目和费用确认。';
  const evidence = clues[source.id]?.[index] ?? source.hidden.split(/[。；]/)[0];
  return `${evidence}${/[。！？]$/.test(evidence) ? '' : '。'}你记下了这次问询或观察的结果，下一步检查还需要继续完成。`;
}
export function assessedClues(source: PresetSource): string | undefined {
  const evidence = clues[source.id];
  return evidence ? `${[...new Set(evidence)].join('')}你记下了已核实的病史与体征，专项检查仍有项目尚未完成。` : undefined;
}
