export function eventOptionLabel(eventId:string,optionId:string,fallback:string):string {
 const labels=EVENT_DIALOGUE[eventId]?.labels;
 const suffix=optionId.slice(eventId.length+1);
 if(!labels||!/^[a-e]$/.test(suffix)||!optionId.startsWith(`${eventId}-`))return fallback;
 return labels[suffix.charCodeAt(0)-97]??fallback;
}
