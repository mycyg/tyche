export function conditionMet(
  facts: Record<string, unknown>,
  c?: Condition,
  cash = 0,
  relations: Record<string, number> = {},
): boolean {
  return (
    !c ||
    ((!c.all || c.all.every((x) => !!facts[x])) &&
      (!c.any || c.any.some((x) => !!facts[x])) &&
      (!c.none || c.none.every((x) => !facts[x])) &&
      (c.cash === undefined || cash >= c.cash) &&
      (!c.relation || (relations[c.relation[0]] ?? 0) >= c.relation[1]))
  );
}
