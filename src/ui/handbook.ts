export function searchHandbook(query: string) {
  const words = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  const titleMatches = (title: string) => words.filter(word => title.toLocaleLowerCase().includes(word)).length;
  return HANDBOOK.filter(chapter => words.every(word => [chapter.title, ...chapter.paragraphs].join(' ').toLocaleLowerCase().includes(word)))
    .sort((a, b) => titleMatches(b.title) - titleMatches(a.title));
}

export function handbookTopicForHint(id:string):string {
  return ({leave:'请假','night-active':'夜班',ap:'预支',fatigue:'体力',san:'精神',overstay:'住院超期',debt:'债务',night:'夜班'} as Record<string,string>)[id.split(':')[0]]??'';
}

export function contextualHelp(r: Run,dismissed:readonly string[]=[]): {id:string;title:string;text:string} | undefined {
  if (r.phase !== 'play') return;
  const tips:{id:string;title:string;text:string}[]=[];
  if (isFullDayLeave(r)) tips.push({id:`leave:${r.day}`,title:'今天已批准停诊休息',text:'常规临床工作已交给同事，不能预支行动。到期账单和私人事务仍需处理；选择中若标有行动消耗，仍可能透支。'});
  if (r.shiftPhase === '夜班') tips.push({id:`night-active:${r.day}:${r.nightMinutes<=0?'empty':'working'}`,title:r.nightMinutes <= 0 ? '夜班时间已用完' : `夜班还剩 ${r.nightMinutes} 分钟`,text:r.nightMinutes <= 0 ? '新到急诊只能先电话交代并请二线接手，不能记成已完成床旁检查。已开始的救治可以继续，但超时处置仍额外消耗体力与精神。' : '夜班按确认的处置耗时扣分钟，不扣白班行动值。阅读病历不扣分钟，确认处置后才计时。'});
  if (r.shiftPhase!=='夜班'&&!isFullDayLeave(r)&&r.ap <= 2 && r.day < RULES.days) tips.push({id:`ap:${r.day}`,title:'行动值快用完了',text:'先看排班表的次日预计值。预支会扣明天的行动和本局状态上限；行动不足仍处置，则承担透支代价。'});
  if (r.vitals.stamina < 50) tips.push({id:`fatigue:${r.day}:${r.vitals.stamina<30?'severe':'low'}`,title:'体力不足会影响检定',text:'看「角色」确认疲劳影响。咖啡和午睡能恢复当前体力，但补不回已经降低的上限。'});
  if (r.vitals.san < 50) tips.push({id:`san:${r.day}:${r.vitals.san<30?'severe':'low'}`,title:'你开始误认周围的动静',text:'精神状态会影响社交检定和环境表现；重要检查结果仍可在病历夹里逐项核对。'});
  if (r.patients.some(p=>p.active && (p.inpatient||r.facts[`awaiting-bed:${p.uid}`])&&r.day-p.admitted+1>p.expectedDays)) tips.push({id:`overstay:${r.day}`,title:'有患者超过预计住院天数',text:'查看住院台账，复核继续住院的依据并说明计划。预算超期不等于可以安全出院。'});
  if (r.debt>0) tips.push({id:`debt:${r.day}:${r.uncoveredDays?'uncovered':'interest'}`,title:r.uncoveredDays?'近期收入已经不够付利息':'借款开始计息',text:'角色页列出当日收入、近期日均收入、利息和负债。借到的钱不算收入；连续两次结算，近期日均收入都不够付当天利息，会结束本局。'});
  if (r.shiftPhase!=='夜班'&&hasPlannedNight(r)) tips.push({id:`night:${r.day}`,title:'今天还有夜班',text:'处理完白班后进入夜班。夜班看剩余分钟，不再扣行动值；也要给明天留出恢复余地。'});
  return tips.find(t=>!dismissed.includes(t.id));
}
